def normalize_lang(lang: str) -> str:
    code = (lang or '').strip().lower()
    return code if code in SUPPORTED_LANGUAGES else 'en'


def is_rtl(lang: str) -> bool:
    return normalize_lang(lang) == 'ar'


def tr(lang: str, key: str, **kwargs) -> str:
    norm = normalize_lang(lang)
    table = STRINGS.get(norm, STRINGS['en'])
    template = table.get(key) or STRINGS['en'].get(key) or key
    return template.format(**kwargs) if kwargs else template


def format_date(dt: Union[datetime.datetime, datetime.date], lang: str) -> str:
    norm = normalize_lang(lang)
    wd = dt.weekday()
    mo = dt.month - 1
    if norm == 'ar':
        return f'{AR_WEEKDAYS[wd]}، {dt.day} {AR_MONTHS[mo]} {dt.year}'
    if norm == 'fr':
        return f'{FR_WEEKDAYS[wd]} {dt.day} {FR_MONTHS[mo]} {dt.year}'
    return f'{EN_WEEKDAYS[wd]}, {EN_MONTHS[mo]} {dt.day}, {dt.year}'
